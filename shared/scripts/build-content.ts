/**
 * Regenerates the content bundled in the teacher app:
 *   teacher/assets/lessons/*.json                                   the starter lessons
 *   teacher/src/features/library/infrastructure/starterLessons.generated.ts   imports them
 *   teacher/src/features/pictures/infrastructure/twemojiArt.generated.ts      SVG art by icon id
 *
 * Run: npm --prefix shared run build:content
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { SUBJECT_ICONS, UI_ICONS } from '@mimikai/contracts';
import { LEXICON } from '@mimikai/exercise-engine';
import { STARTER_REQUESTS, buildStarterLesson, lessonFileText } from './starterLessons';

const ROOT = path.resolve(__dirname, '../..');
const LESSONS_DIR = path.join(ROOT, 'teacher/assets/lessons');
const STARTER_MODULE = path.join(ROOT, 'teacher/src/features/library/infrastructure/starterLessons.generated.ts');
const ART_MODULE = path.join(ROOT, 'teacher/src/features/pictures/infrastructure/twemojiArt.generated.ts');
const TWEMOJI = path.dirname(require.resolve('@twemoji/svg/package.json'));

/** The sparkles on the "Crear con IA" button. */
const AI_ICON = '2728';

const HEADER = '// Generated by shared/scripts/build-content.ts. Do not edit: run `npm --prefix shared run build:content`.\n';

function writeLessons(): void {
  rmSync(LESSONS_DIR, { recursive: true, force: true });
  mkdirSync(LESSONS_DIR, { recursive: true });
  const lessons = STARTER_REQUESTS.map(buildStarterLesson);
  for (const lesson of lessons) writeFileSync(path.join(LESSONS_DIR, `${lesson.id}.json`), lessonFileText(lesson));
  const names = lessons.map((l, i) => ({ id: l.id, name: `lesson${i}` }));
  const module = [
    HEADER,
    ...names.map(({ id, name }) => `import ${name} from '../../../../assets/lessons/${id}.json';`),
    '',
    '/** The starter lesson files, still unchecked: the repository decodes them like any other file. */',
    `export const STARTER_LESSON_FILES: readonly unknown[] = [${names.map((n) => n.name).join(', ')}];`,
    '',
  ].join('\n');
  mkdirSync(path.dirname(STARTER_MODULE), { recursive: true });
  writeFileSync(STARTER_MODULE, module);
  const cards = lessons.reduce((n, l) => n + l.cards.length, 0);
  console.log(`${lessons.length} starter lessons, ${cards} cards → ${path.relative(ROOT, LESSONS_DIR)}`);
}

/** Twemoji SVGs are already small; drop line breaks so each one is a single short string. */
const compact = (svg: string): string => svg.replace(/\r?\n\s*/g, '').trim();

function writeArt(): void {
  const icons = [...new Set([...LEXICON.map((w) => w.icon), ...Object.values(UI_ICONS), ...Object.values(SUBJECT_ICONS), AI_ICON])].sort();
  const available = new Set(readdirSync(TWEMOJI).filter((f) => f.endsWith('.svg')));
  const missing = icons.filter((id) => !available.has(`${id}.svg`));
  if (missing.length > 0) throw new Error(`Twemoji has no art for: ${missing.join(', ')}`);
  const entries = icons.map((id) => `  '${id}': ${JSON.stringify(compact(readFileSync(path.join(TWEMOJI, `${id}.svg`), 'utf8')))},`);
  const module = [
    HEADER,
    '/**',
    ' * Twemoji SVG art (graphics © Twitter, Inc. and other contributors, CC-BY 4.0,',
    ' * https://github.com/jdecked/twemoji) for every picture the exercise engine can use.',
    ' */',
    'export const TWEMOJI_ART: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
  mkdirSync(path.dirname(ART_MODULE), { recursive: true });
  writeFileSync(ART_MODULE, module);
  console.log(`${icons.length} icons, ${(Buffer.byteLength(module) / 1024).toFixed(0)} KB → ${path.relative(ROOT, ART_MODULE)}`);
}

writeLessons();
writeArt();
